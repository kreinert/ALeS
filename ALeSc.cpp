// Heuristic algorithm for generating lengths of the seeds given minimum length m and maximum length M
void assign_seed_lengths(int* length_arr, int nSeeds, int m_val, int M_val)
{
	int* cnt = new int[100];
	for (int i = 0; i < 100; i++)
		cnt[i] = 0;
	int temp = M_val;
	length_arr[0] = m_val;
	length_arr[nSeeds - 1] = M_val;
	cnt[length_arr[0]] = 1;
	cnt[length_arr[nSeeds - 1]] = 1;
	bool isReachedToEnd = false;
	for (int i = 1; i < nSeeds - 1; i++) {
		if (!isReachedToEnd) {
			length_arr[i] = (int)ceil((double)(length_arr[i - 1] + M_val) / 2.0);
		}
		else {
			length_arr[i] = temp;
		}
		if (cnt[length_arr[i]] < (int)ceil((double)(nSeeds) / (pow(2.0, M_val - length_arr[i] + 1)))) {
			cnt[length_arr[i]] = cnt[length_arr[i]] + 1;
		}
		else if (cnt[length_arr[i]] == (int)ceil((double)(nSeeds) / (pow(2.0, M_val - length_arr[i] + 1)))) {
			isReachedToEnd = true;
			length_arr[i] = length_arr[i] - 1;
			temp = length_arr[i];
			cnt[length_arr[i]] = cnt[length_arr[i]] + 1;
		}
		else {
			isReachedToEnd = true;
			cnt[length_arr[i]] = cnt[length_arr[i]] + 1;
		}
	}
	qsort(length_arr, nSeeds, sizeof(int), compare);
	for (int i = 0; i < nSeeds; i++)
		length_arr[i] = palindrome_legal_len(length_arr[i]);
	delete[] cnt;
}

void randomize_seed_lengths(int* length_arr, int nSeeds, int m_val, int M_val, int weight)
{
	int hi = M_val;
	if (hi > upperBound) hi = upperBound;
	if (hi > (int)N) hi = (int)N;
	int lo = m_val;
	if (lo < weight) lo = weight;
	if (lo < cl) lo = cl;
	if (lo > hi) lo = hi;
	if (lo < weight) lo = weight;
	if (hi < lo) hi = lo;
	for (int i = 0; i < nSeeds; i++)
		length_arr[i] = palindrome_legal_len(lo + ale_rand() % (hi - lo + 1));
}

void pick_restart_lengths(int* length_arr, int nSeeds, int weight, int perm)
{
	int hi = upperBound;
	if (hi > (int)N - 1) hi = (int)N - 1;
	int lo = weight;
	if (lo < cl) lo = cl;
	if (lo > hi) lo = hi;
	for (int i = 0; i < nSeeds; i++) {
		if (i < nFrozen) {
			length_arr[i] = frozenLen[i];
			continue;
		}
		if (perm % 2 == 0)
			length_arr[i] = palindrome_legal_len(hi);
		else
			length_arr[i] = palindrome_legal_len(lo + ale_rand() % (hi - lo + 1));
	}
}

